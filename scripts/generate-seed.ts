// Generates supabase/seed.sql from the shared data (categories, cities, prices).
// Run from project root:  npm run seed:generate   (needs Node 22.6+)
// Then run supabase/seed.sql in the Supabase SQL Editor (once, on an empty DB).

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import {
  districts,
  cities,
  OTHER_LOCALITY,
  categories,
  AD_DURATIONS,
  DEFAULT_AD_PRICES,
  PROVIDER_PLAN,
  ADDONS,
  RISHTA_PROFILE_PLAN,
} from '../packages/shared/src/index.ts';

const q = (v: string | null | undefined): string =>
  v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`;
const j = (v: unknown): string => `${q(JSON.stringify(v))}::jsonb`;

const out: string[] = [];
out.push('-- AUTO-GENERATED by scripts/generate-seed.ts. Do not edit by hand.');
out.push('begin;');

// ---- Locations ----
districts.forEach((d, i) => {
  out.push(
    `insert into districts (slug, name_en, name_ur, sort_order) values (${q(d.slug)}, ${q(d.name.en)}, ${q(d.name.ur)}, ${i});`,
  );
});
cities.forEach((c, i) => {
  out.push(
    `insert into cities (district_id, slug, name_en, name_ur, sort_order) select id, ${q(c.slug)}, ${q(c.name.en)}, ${q(c.name.ur)}, ${i} from districts where slug = ${q(c.district)};`,
  );
  [...c.localities, OTHER_LOCALITY].forEach((l, k) => {
    const sort = l.slug === 'other' ? 999 : k;
    out.push(
      `insert into localities (city_id, slug, name_en, name_ur, sort_order) select id, ${q(l.slug)}, ${q(l.name.en)}, ${q(l.name.ur)}, ${sort} from cities where slug = ${q(c.slug)};`,
    );
  });
});

// ---- Categories, sub-categories, fields ----
categories.forEach((c, i) => {
  out.push(
    `insert into categories (model, slug, name_en, name_ur, icon, show_on_home, sort_order) values (${q(c.model)}, ${q(c.slug)}, ${q(c.name.en)}, ${q(c.name.ur)}, ${q(c.icon)}, ${c.showOnHome}, ${i});`,
  );
  c.subcategories.forEach((s, k) => {
    out.push(
      `insert into categories (parent_id, model, slug, name_en, name_ur, sort_order) select id, ${q(c.model)}, ${q(c.slug + '--' + s.slug)}, ${q(s.name.en)}, ${q(s.name.ur)}, ${k} from categories where slug = ${q(c.slug)};`,
    );
  });
  (c.fields ?? []).forEach((f, k) => {
    out.push(
      `insert into category_fields (category_id, key, label_en, label_ur, type, options, unit_en, unit_ur, is_required, sort_order) select id, ${q(f.key)}, ${q(f.label.en)}, ${q(f.label.ur)}, ${q(f.type)}, ${f.options ? j(f.options) : 'null'}, ${q(f.unit?.en)}, ${q(f.unit?.ur)}, ${!!f.required}, ${k} from categories where slug = ${q(c.slug)};`,
    );
  });
});

// ---- Default pricing ----
for (const model of ['buy_sell', 'vehicles', 'property', 'jobs']) {
  for (const d of AD_DURATIONS) {
    out.push(
      `insert into pricing (model, duration_days, price) values (${q(model)}, ${d}, ${DEFAULT_AD_PRICES[d]});`,
    );
  }
}
for (const model of ['services', 'business']) {
  out.push(
    `insert into pricing (model, duration_days, price) values (${q(model)}, ${PROVIDER_PLAN.days}, ${PROVIDER_PLAN.prices[model]});`,
  );
}
Object.values(ADDONS).forEach((a) => {
  out.push(
    `insert into addons (key, name_en, name_ur, price) values (${q(a.key)}, ${q(a.name.en)}, ${q(a.name.ur)}, ${a.price});`,
  );
});

// ---- Site settings ----
const settings: Record<string, unknown> = {
  'public.free_mode': {
    enabled: false,
    starts_at: null,
    ends_at: null,
    days_by_model: { buy_sell: 30, vehicles: 30, property: 30, jobs: 30, services: 3650, business: 3650 },
    models: ['buy_sell', 'vehicles', 'property', 'jobs', 'services', 'business'],
    category_slugs: null,
    max_free_ads_per_phone: 3,
    banner: { en: 'Launch offer: post your ads free', ur: 'لانچ آفر: اشتہار بالکل مفت لگائیں' },
  },
  'public.rishta_free_mode': { enabled: false },
  'public.rishta_plan': RISHTA_PROFILE_PLAN,
  'public.contact': { phone: '0307 2849373', whatsapp: '0307 2849373', email: 'apnaokarapk@gmail.com', address: null },
  'public.social': { facebook: null, whatsapp_group: null, whatsapp_channel: null, instagram: null, youtube: null },
  'public.payment_accounts': {
    jazzcash: { title: 'Shagufta Latif', number: '0307 2849373' },
    easypaisa: { title: 'Shagufta Latif', number: '0307 2849373' },
    nayapay: { title: 'Shagufta Latif', number: '0307 2849373' },
    bank: { bank_name: 'Meezan Bank', title: 'Shoaib Latif', account: '29020110227425', iban: null },
  },
  'public.offer_bar': { enabled: false, en: '', ur: '' },
  'public.app_links': { play_store: null, app_store: null },
};
for (const [key, value] of Object.entries(settings)) {
  out.push(`insert into site_settings (key, value) values (${q(key)}, ${j(value)}) on conflict (key) do update set value = excluded.value;`);
}

// ---- Home page sections (order and on/off managed in admin) ----
const sections = [
  'top_bar', 'offer_bar', 'hero', 'trust_points', 'categories', 'featured', 'wide_banner',
  'fresh_ads', 'seasonal', 'services', 'rishta', 'city_tabs', 'jobs', 'businesses', 'how_it_works',
  'cities', 'brands', 'community_app', 'blog', 'faq', 'seo_text',
];
sections.forEach((key, i) => {
  const enabled = key !== 'seasonal' && key !== 'offer_bar';
  out.push(
    `insert into homepage_sections (key, is_enabled, sort_order) values (${q(key)}, ${enabled}, ${i}) on conflict (key) do update set sort_order = excluded.sort_order;`,
  );
});

// ---- Static pages (content filled later from admin) ----
const pages: [string, string, string][] = [
  ['about', 'About Us', 'ہمارے بارے میں'],
  ['contact', 'Contact Us', 'رابطہ کریں'],
  ['how-it-works', 'How It Works', 'طریقہ کار'],
  ['faq', 'FAQ', 'عام سوالات'],
  ['pricing', 'Pricing', 'قیمتیں'],
  ['safety', 'Safety Tips', 'حفاظتی ہدایات'],
  ['community', 'Join Our Community', 'کمیونٹی میں شامل ہوں'],
  ['advertise', 'Advertise With Us', 'ہمارے ساتھ اشتہار دیں'],
  ['terms', 'Terms and Conditions', 'شرائط و ضوابط'],
  ['privacy', 'Privacy Policy', 'پرائیویسی پالیسی'],
  ['posting-rules', 'Posting Rules', 'اشتہار کے قواعد'],
  ['refund-policy', 'Refund Policy', 'رقم واپسی کی پالیسی'],
  ['disclaimer', 'Disclaimer', 'دستبرداری'],
];
pages.forEach(([slug, en, ur]) => {
  out.push(`insert into pages (slug, title_en, title_ur) values (${q(slug)}, ${q(en)}, ${q(ur)});`);
});

// ---- Storage buckets ----
out.push(`insert into storage.buckets (id, name, public) values ('listing-images', 'listing-images', true) on conflict do nothing;`);
out.push(`insert into storage.buckets (id, name, public) values ('banners', 'banners', true) on conflict do nothing;`);
out.push(`insert into storage.buckets (id, name, public) values ('blog', 'blog', true) on conflict do nothing;`);
out.push(`insert into storage.buckets (id, name, public) values ('payment-screenshots', 'payment-screenshots', false) on conflict do nothing;`);
out.push(`insert into storage.buckets (id, name, public) values ('rishta-photos', 'rishta-photos', false) on conflict do nothing;`);

out.push('commit;');

const here = dirname(fileURLToPath(import.meta.url));
const target = join(here, '..', 'supabase', 'seed.sql');
writeFileSync(target, out.join('\n') + '\n', 'utf8');
console.log(`Wrote ${out.length} lines to ${target}`);
