// Packs supabase/migrations/*.sql and supabase/seed.sql into the website
// (apps/web/src/lib/sql/bundle.generated.ts) so the live site can set up and
// update its own database from Admin, without anyone handling the DB password.
// Runs automatically before every website build (apps/web "prebuild").
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const migDir = join(root, 'supabase', 'migrations');
const migrations = readdirSync(migDir)
  .filter((f) => f.endsWith('.sql'))
  .sort()
  .map((name) => ({ name, sql: readFileSync(join(migDir, name), 'utf8') }));
const seed = readFileSync(join(root, 'supabase', 'seed.sql'), 'utf8');

const out = join(root, 'apps', 'web', 'src', 'lib', 'sql', 'bundle.generated.ts');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `// GENERATED by scripts/bundle-sql.mjs. Do not edit; edit supabase/migrations or supabase/seed.sql.\n` +
    `export const MIGRATIONS: { name: string; sql: string }[] = ${JSON.stringify(migrations, null, 0)};\n` +
    `export const SEED_SQL: string = ${JSON.stringify(seed)};\n`,
);
console.log(`bundled ${migrations.length} migrations + seed -> ${out.replace(root, '.')}`);
